// Build once: render the approved content snapshot into an immutable static bundle
// with a visible release ID and a file-hash manifest.
import { mkdir, readFile, rm, writeFile, appendFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { readJson, sha256, hashBundle, MANIFEST_FILE } from './lib.mjs';
import { validateContent } from './validate.mjs';

const esc = (s) => String(s).replace(/[&<>"']/g, (ch) =>
  ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));

function git(args) {
  try { return execFileSync('git', args, { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); }
  catch { return ''; }
}

export function resolveBuildInputs(env = process.env, content) {
  const sourceRevision = env.GITHUB_SHA || git(['rev-parse', 'HEAD']) || 'local';
  let builtAt;
  if (env.SOURCE_DATE_EPOCH) builtAt = new Date(Number(env.SOURCE_DATE_EPOCH) * 1000).toISOString();
  else builtAt = git(['log', '-1', '--format=%cI']) || content.approval.approvedAt;
  builtAt = new Date(builtAt).toISOString();
  const siteUrl = (env.SITE_URL || 'https://aurevia.invalid').replace(/\/+$/, '');
  return { sourceRevision, builtAt, siteUrl };
}

export function makeReleaseId(content, { builtAt, sourceRevision }) {
  const day = builtAt.slice(0, 10).replaceAll('-', '');
  const rev = sourceRevision === 'local' ? 'local' : sourceRevision.slice(0, 7);
  return `${content.trialId.replace(/[^A-Za-z0-9]/g, '')}-${content.contentVersion}-${day}-${rev}`;
}

function head({ title, lang, cssHref, canonical, alternates }) {
  return `<!doctype html>
<html lang="${esc(lang)}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<link rel="stylesheet" href="${cssHref}">
${canonical ? `<link rel="canonical" href="${esc(canonical)}">\n` : ''}${alternates.map((a) =>
    `<link rel="alternate" hreflang="${esc(a.hreflang)}" href="${esc(a.href)}">`).join('\n')}
</head>`;
}

function marketNav(markets, currentPath, label) {
  return `<nav aria-label="${esc(label)}"><ul>
${markets.map(([, m]) => `  <li><a href="${m.path}" hreflang="${esc(m.lang)}"${m.path === currentPath ? ' aria-current="page"' : ''}>${esc(m.country)} · ${esc(m.lang)}</a></li>`).join('\n')}
</ul></nav>`;
}

function marketPage(content, id, m, ctx) {
  const s = content.status;
  return `${head({ title: `${m.title} | ${m.statusLabel[s]}`, lang: m.lang, cssHref: ctx.cssHref,
    canonical: ctx.siteUrl + m.path, alternates: ctx.alternates })}
<body>
<div class="banner">${esc(m.disclaimer)}</div>
<main>
<div class="brand">${esc(content.product)} · ${esc(content.trialId)}</div>
<h1>${esc(m.title)}</h1>
<p>${esc(m.summary)}</p>
<section class="card" aria-labelledby="status-h">
<h2 id="status-h">${esc(m.statusHeading)}</h2>
<span class="status ${s}" data-status="${s}">${esc(m.statusLabel[s])}</span>
<p class="detail">${esc(m.statusDetail[s])}</p>
</section>
<section class="card">
<dl>
<dt>${esc(m.approvedLabel)}</dt><dd>${esc(content.approval.reference)} · v${esc(content.contentVersion)}</dd>
<dt>${esc(m.releaseLabel)}</dt><dd data-release-id>${esc(ctx.releaseId)}</dd>
</dl>
</section>
${marketNav(ctx.markets, m.path, m.marketLabel)}
<footer>${esc(m.disclaimer)}</footer>
</main>
</body>
</html>
`;
}

function selectorPage(content, ctx) {
  return `${head({ title: `${content.product} ${content.trialId}`, lang: 'en', cssHref: ctx.cssHref,
    canonical: ctx.siteUrl + '/', alternates: ctx.alternates })}
<body>
<div class="banner">Fictional demonstration site. Not medical information.</div>
<main>
<div class="brand">${esc(content.product)} · ${esc(content.trialId)}</div>
<h1>Choose your market</h1>
<p>Each market has its own approved content and language. We do not redirect you automatically.</p>
${marketNav(ctx.markets, null, 'Markets')}
<footer>Release <span data-release-id>${esc(ctx.releaseId)}</span></footer>
</main>
</body>
</html>
`;
}

function notFoundPage(ctx) {
  return `${head({ title: 'Page not found', lang: 'en', cssHref: ctx.cssHref, canonical: null, alternates: [] })}
<body>
<div class="banner">Fictional demonstration site. Not medical information.</div>
<main>
<h1>Page not found</h1>
<p><a href="/">Choose your market</a></p>
<footer>Release <span data-release-id>${esc(ctx.releaseId)}</span></footer>
</main>
</body>
</html>
`;
}

function headersFile(releaseId, markets) {
  // Paths are disjoint so no header is set twice for one URL.
  const revalidate = 'public, max-age=0, must-revalidate';
  return `# Generated by scripts/build.mjs — do not edit by hand.
/*
  X-Release-Id: ${releaseId}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy: default-src 'none'; style-src 'self'; img-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/
  Cache-Control: ${revalidate}

/release.json
  Cache-Control: ${revalidate}
  Access-Control-Allow-Origin: *

/${MANIFEST_FILE}
  Cache-Control: ${revalidate}
  Access-Control-Allow-Origin: *

${markets.map(([, m]) => `${m.path}*\n  Cache-Control: ${revalidate}`).join('\n\n')}
`;
}

export async function build({ contentPath = 'content/trial.json', outDir = 'dist', env = process.env } = {}) {
  const content = await readJson(contentPath);
  const errors = validateContent(content);
  if (errors.length) throw new Error(`content is not releasable:\n  - ${errors.join('\n  - ')}`);

  const inputs = resolveBuildInputs(env, content);
  const releaseId = makeReleaseId(content, inputs);
  const markets = Object.entries(content.markets);

  await rm(outDir, { recursive: true, force: true });
  const write = async (rel, data) => {
    const full = join(outDir, rel);
    await mkdir(dirname(full), { recursive: true });
    await writeFile(full, data);
  };

  // Content-hashed stylesheet: a new file gets a new URL, so it can be cached forever.
  const css = await readFile('site/styles.css');
  const cssName = `assets/styles.${sha256(css).slice(0, 10)}.css`;
  await write(cssName, css);

  const ctx = {
    releaseId, siteUrl: inputs.siteUrl, cssHref: '/' + cssName, markets,
    alternates: [
      ...markets.map(([, m]) => ({ hreflang: m.lang, href: inputs.siteUrl + m.path })),
      { hreflang: 'x-default', href: inputs.siteUrl + '/' },
    ],
  };

  await write('index.html', selectorPage(content, ctx));
  await write('404.html', notFoundPage(ctx));
  for (const [id, m] of markets) await write(m.path.slice(1) + 'index.html', marketPage(content, id, m, ctx));

  const release = {
    releaseId,
    trialId: content.trialId,
    contentVersion: content.contentVersion,
    status: content.status,
    approval: {
      reference: content.approval.reference,
      contentVersion: content.approval.contentVersion,
      approvedAt: content.approval.approvedAt,
    },
    validFrom: content.validFrom,
    validUntil: content.validUntil,
    markets: markets.map(([id, m]) => ({ id, lang: m.lang, path: m.path })),
    sourceRevision: inputs.sourceRevision,
    builtAt: inputs.builtAt,
    siteUrl: inputs.siteUrl,
  };
  await write('release.json', JSON.stringify(release, null, 2) + '\n');
  await write('_headers', headersFile(releaseId, markets));

  const { files, digest } = await hashBundle(outDir);
  const manifest = { releaseId, bundleDigest: digest, algorithm: 'sha256', files };
  await write(MANIFEST_FILE, JSON.stringify(manifest, null, 2) + '\n');

  return { releaseId, digest, fileCount: Object.keys(files).length, release };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const r = await build({ contentPath: process.argv[2] ?? 'content/trial.json' });
    console.log(`✓ Built release ${r.releaseId}`);
    console.log(`  status:        ${r.release.status} (content v${r.release.contentVersion}, ${r.release.approval.reference})`);
    console.log(`  files:         ${r.fileCount}`);
    console.log(`  bundle digest: ${r.digest}`);
    if (process.env.GITHUB_OUTPUT) {
      await appendFile(process.env.GITHUB_OUTPUT, `release_id=${r.releaseId}\nbundle_digest=${r.digest}\n`);
    }
  } catch (e) {
    console.error(`✗ Build refused: ${e.message}`);
    process.exitCode = 1;
  }
}
